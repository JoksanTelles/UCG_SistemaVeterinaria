    private void btnCrearRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearRegistroActionPerformed
        // TODO add your handling code here:
        String nombre = jtfNombre.getText().trim();
        String especie = cbEspecie.getSelectedItem().toString();
        String raza = cbRaza.getSelectedItem().toString();
        String sexo = cbSexo.getSelectedItem().toString();
        double peso = Double.parseDouble(jtfPeso.getText().trim());
        String vacuna = cbVacuna.getSelectedItem().toString();
        int edad = Integer.parseInt(spinEdad.getValue().toString());

        if (nombre.isEmpty() || jtfPeso.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete todos los campos obligatorios.");
            return;
        }
        
        if (cbCliente.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un cliente.");
            return;
        }
        
        ClientesPOJO clienteSeleccionado = (ClientesPOJO) cbCliente.getSelectedItem();
        int idCliente = clienteSeleccionado.getIdCliente();

        MascotasPOJO mascota = new MascotasPOJO();
        mascota.setNombre(nombre);
        mascota.setEspecie(especie);
        mascota.setRaza(raza);
        mascota.setSexo(sexo);
        mascota.setPeso(peso);
        mascota.setVacuna(vacuna);
        mascota.setEdad(edad);
        mascota.setIdCliente(idCliente);

        if (estado == 1) {
            // Modo Crear
            if (mascotasDAO.registrarMascota(mascota)) {
                limpiarCampos();
                listarMascotas();
            }
        } else {
            // Modo Editar (utiliza el id_actual que guardó btnEditar)
            mascota.setIdMascota(id_actual);
            if (mascotasDAO.modificarMascota(mascota)) {
                JOptionPane.showMessageDialog(this, "Mascota actualizada correctamente.");
                limpiarCampos(); // limpiarCampos() ya regresa estado a 1 e id_actual a -1
                listarMascotas();
            }
        }
    }//GEN-LAST:event_btnCrearRegistroActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        int fila = TablaMascotas.getSelectedRow();

        // Si no ha seleccionado ninguna fila de la tabla, avisamos y salimos
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una mascota de la tabla para editar.");
            return;
        }

        id_actual = Integer.parseInt(TablaMascotas.getValueAt(fila, 0).toString());

        estado = 2;
        btnCrearRegistro.setText("Guardar cambios");

        jtfNombre.setText(TablaMascotas.getValueAt(fila, 1).toString());
        cbEspecie.setSelectedItem(TablaMascotas.getValueAt(fila, 2).toString());
        cbRaza.setSelectedItem(TablaMascotas.getValueAt(fila, 3).toString());
        cbSexo.setSelectedItem(TablaMascotas.getValueAt(fila, 4).toString());
        jtfPeso.setText(TablaMascotas.getValueAt(fila, 5).toString());
        cbVacuna.setSelectedItem(TablaMascotas.getValueAt(fila, 6).toString());
        spinEdad.setValue(Integer.parseInt(TablaMascotas.getValueAt(fila, 7).toString()));
        
        int idClienteTab = Integer.parseInt(TablaMascotas.getValueAt(fila, 8).toString());
        for (int i = 0; i < cbCliente.getItemCount(); i++) {
            ClientesPOJO cli = (ClientesPOJO) cbCliente.getItemAt(i);
            if (cli.getIdCliente() == idClienteTab) {
                cbCliente.setSelectedIndex(i);
                break;
            }
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = TablaMascotas.getSelectedRow();

        // 1. Validar si hay una fila seleccionada
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un cliente de la tabla para eliminar.");
            return;
        }

        // 2. Obtener el ID del cliente (columna 0) y su nombre (columna 1) para el mensaje
        int idEliminar = Integer.parseInt(TablaMascotas.getValueAt(fila, 0).toString());
        String nombreCliente = TablaMascotas.getValueAt(fila, 1).toString();

        // 3. Confirmar la eliminación
        int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de eliminar al cliente " + nombreCliente + "?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        // 4. Si el usuario confirma (presiona Sí)
        if (confirmacion == JOptionPane.YES_OPTION) {
            if (mascotasDAO.eliminarMascota(idEliminar)) {
                limpiarCampos();   // Restablece los formularios por si estaba cargado en edición
                listarMascotas();  // Vuelve a consultar la base de datos y refresca la tabla
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

