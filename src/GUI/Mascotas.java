    public void listarMascotas() {
        List<MascotasPOJO> mascota = mascotasDAO.listarMascotas();
        modelo = (DefaultTableModel) TablaMascotas.getModel();
        modelo.setRowCount(0);

        for (int i = 0; i< mascota.size(); i++) {
            Object[] fila = new Object[9];
            
            fila[0] = mascota.get(i).getIdMascota();
            fila[1] = mascota.get(i).getNombre();
            fila[2] = mascota.get(i).getEspecie();
            fila[3] = mascota.get(i).getRaza();
            fila[4] = mascota.get(i).getSexo();
            fila[5] = mascota.get(i).getPeso();
            fila[6] = mascota.get(i).getVacuna();
            fila[7] = mascota.get(i).getEdad();
            fila[8] = mascota.get(i).getIdCliente();
            
            modelo.addRow(fila);
        }
    }
    
    public void inicializarEspecies() {
        cbEspecie.removeAllItems();
        cbEspecie.addItem("Conejo");
        cbEspecie.addItem("Gato");
        cbEspecie.addItem("Hamster");
        cbEspecie.addItem("Tortuga");
        cbEspecie.addItem("Perro");

        // Listener para cambiar las razas al seleccionar una especie
        cbEspecie.addItemListener(e -> {
            if (e.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
                actualizarRazas();
            }
        });

        actualizarRazas();
        
        cbEspecie.setSelectedIndex(-1);
        cbRaza.setSelectedIndex(-1);
    }
    
    public void actualizarRazas() {
        cbRaza.removeAllItems();
        String especieSeleccionada = (String) cbEspecie.getSelectedItem();

        if (especieSeleccionada == null) return;

        switch (especieSeleccionada) {
            case "Conejo":
                cbRaza.addItem("Head-Lop");
                cbRaza.addItem("Angora");
                cbRaza.addItem("Holandés Enano");
                break;
            case "Gato":
                cbRaza.addItem("Siamés");
                cbRaza.addItem("Persa");
                cbRaza.addItem("Maine Coon");
                break;
            case "Hamster":
                cbRaza.addItem("Sirio");
                cbRaza.addItem("Ruso");
                cbRaza.addItem("Roborovski");
                break;
            case "Tortuga":
                cbRaza.addItem("Tortuga Rusa");
                cbRaza.addItem("Tortuga de Patas Rojas");
                cbRaza.addItem("Tortuga Sulcata");
                break;
            case "Perro":
                cbRaza.addItem("Labrador");
                cbRaza.addItem("Poodle");
                cbRaza.addItem("Pastor Alemán");
                break;
        }
    }
    
    public void cargarClientesComboBox() {
        ClientesDAO clienteDAO = new ClientesDAO();
        List<ClientesPOJO> listaClientes = clienteDAO.listarClientes();
        cbCliente.removeAllItems();

        for (ClientesPOJO cliente : listaClientes) {
            cbCliente.addItem(cliente); // Se llena directamente con el POJO gracias al toString()
        }
        cbCliente.setSelectedIndex(-1);
    }
    
